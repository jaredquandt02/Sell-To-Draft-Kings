function expand(
  rows: Array<[string, string]>,
  position: Position,
  start: number,
): NflPlayerSeed[] {
  return rows.map(([name, nflTeam], i) => ({
    externalId: `nfl-${start + i}`,
    name,
    position,
    nflTeam,
  }));
}

export const NFL_PLAYER_SEEDS: NflPlayerSeed[] = [
  ...expand(QBS, "QB", 1),
  ...expand(RBS, "RB", 1 + QBS.length),
  ...expand(WRS.filter((w, i, arr) => arr.findIndex((x) => x[0] === w[0]) === i), "WR", 1 + QBS.length + RBS.length),
  ...expand(TES, "TE", 200),
  ...expand(KS, "K", 300),
  ...expand(DSTS, "DST", 400),
];
